// POST /analyst: the AI planner's rounds of the analyst loop (reference handler for insight-proxy).
//
// Copied into insight-proxy as src/analyst.js (beside step-schema.json) by deploy/insight-proxy/apply-patch.mjs, which
// routes /analyst to analystFetch (CORS, the proxy's rate limiters and daily spend counter, then handleAnalyst).
// The protocol, the limits and the page loop are in docs/ai-analyst/PROTOCOL.md of the site repository.
//
// What it does: the page sends the file's shape (column names and kinds, never a row) and the ledger texts of the
// steps run so far; the model answers with at most four typed steps {op, args, why} chosen from the ops the engine
// knows (step-schema.json, generated by engine/nl_analyst.py step_schema()); this handler checks every step against
// that schema narrowed to the file's columns and drops anything else. The model never writes a figure: it picks
// steps, the engine computes them in the visitor's tab (nl_analyst.run_steps) and every number on screen comes from
// the engine's ledger. A `why` holding a digit is blanked, so not even the reason can carry a number.
//
// Environment (wrangler.toml [vars] / secrets). The model is DeepSeek when DEEPSEEK_API_KEY is set (the site's own
// worker words /plan and /report with it), else Claude:
//   DEEPSEEK_API_KEY      secret (npx wrangler secret put DEEPSEEK_API_KEY): DeepSeek's chat API (no JSON mode: the answer is parsed leniently)
//   DEEPSEEK_MODEL        default "deepseek-flash" (the proxy's own default); DEEPSEEK_BASE_URL as the proxy reads it
//   ANTHROPIC_API_KEY     secret, used only when DEEPSEEK_API_KEY is not set
//   ANALYST_MODEL         default "claude-opus-5-5" (the Claude path)
//   ANALYST_TIMEOUT_MS    default 25000 (the page waits ANALYST_TIMEOUT_MS + 10 s, see PROTOCOL.md "Timeouts")
//   ANALYST_MAX_TOKENS    default 4000 (thinking is always on for this model and counts against it)
//   ANALYST_EFFORT        default "low"

import STEP_SCHEMA from "./step-schema.json" with { type: "json" };

// the sql argument's length cap, as the schema states it (4000 when the schema has no sql op)
function STEP_SCHEMA_SQL_MAX() {
  for (const v of STEP_SCHEMA.oneOf) {
    const a = v.properties.args.properties.sql;
    if (a && a.maxLength) return a.maxLength;
  }
  return 4000;
}

export const ANALYST_LIMITS = Object.freeze({
  maxBodyBytes: 48 * 1024, // the request: shape + ledger texts, roughly 12k tokens at most
  maxObjectiveChars: 300,
  maxColumns: 60, // measures + dimensions the shape may list
  maxNameChars: 200,
  maxPriorSteps: 40, // steps_so_far kept (the latest)
  maxFigureChars: 160,
  maxFiguresPerStep: 40,
  maxRounds: STEP_SCHEMA["x-max-rounds"] || 3,
  maxStepsPerRound: STEP_SCHEMA["x-max-steps-per-round"] || 4,
  maxWhyChars: 200,
  maxSqlChars: STEP_SCHEMA_SQL_MAX(),
  maxPriorArgsChars: 4600, // a prior sql step's args carry its query
});

