// ------------------------------------------------------------------------------------------ the sql step's check
// A planner's `sql` step (Ask your data with SQL, the site's CONTRACT §5.14) holds one query over the table the engine
// keeps in the visitor's browser, kept_rows, whose columns are the shape's. checkSql refuses anything but ONE read-only
// SELECT/WITH over that table and those columns: no PRAGMA/ATTACH/DETACH/INSERT/UPDATE/DELETE/CREATE/DROP/ALTER/
// REPLACE/VACUUM/load_extension, no second statement, no parameter, no other table (sqlite_master), no function off the
// list. The engine runs the same check again (engine/nl_sql.py check_sql) and the query under a SQLite authorizer, so
// this is a filter, not the fence.
export const SQL_TABLE = "kept_rows";
// The same rules as the engine's nl_sql.check_sql (keep the word lists in step).
const BANNED = new Set(("pragma attach detach insert update delete create drop alter vacuum reindex analyze truncate begin " +
  "commit rollback savepoint release grant revoke trigger load_extension readfile writefile edit fts3_tokenizer").split(" "));
const FUNCTIONS = new Set(("count sum avg min max total group_concat abs round coalesce ifnull nullif iif lower upper length " +
  "substr substring trim ltrim rtrim replace instr strftime date time datetime julianday unixepoch printf format typeof " +
  "sign row_number rank dense_rank percent_rank cume_dist ntile lag lead first_value last_value nth_value like glob " +
  "cast hex quote char unicode likely unlikely").split(" "));
const KEYWORDS = new Set(("select with recursive as from where group by having order asc desc limit offset and or not in is " +
  "null like glob between case when then else end distinct all union intersect except join inner left right full outer cross " +
  "natural on using exists cast over partition window rows range groups unbounded preceding following current row filter " +
  "nulls first last collate escape values integer int real text numeric blob float double varchar char boolean date true " +
  "false within materialized exclude ties others no").split(" "));
const TOKEN = /(\s+)|(--[^\n]*)|(\/\*[\s\S]*?\*\/)|('(?:[^']|'')*')|("(?:[^"]|"")*"|`[^`]*`|\[[^\]]*\])|(\d+(?:\.\d*)?(?:[eE][-+]?\d+)?|\.\d+(?:[eE][-+]?\d+)?)|([A-Za-z_][A-Za-z0-9_]*)|(\|\||<=|>=|<>|!=|==|<<|>>|[-+*/%<>=(),.;~&|])/y;
const KIND_OF = [null, "ws", "lc", "bc", "str", "qid", "num", "word", "op"];

export function tokens(sql) {
  const out = [];
  let i = 0;
  while (i < sql.length) {
    TOKEN.lastIndex = i;
    const m = TOKEN.exec(sql);
    if (!m) {
      const ch = sql[i];
      if ("'\"`[".includes(ch)) return { error: "a quote or bracket is never closed" };
      if (sql.startsWith("/*", i)) return { error: "a comment is never closed" };
      if ("?:@$".includes(ch)) return { error: "parameters are not allowed" };
      return { error: "the character " + JSON.stringify(ch) + " is not allowed" };
    }
    let kind = null;
    for (let g = 1; g < m.length; g++) if (m[g] !== undefined) { kind = KIND_OF[g]; break; }
    if (kind !== "ws" && kind !== "lc" && kind !== "bc") out.push([kind, m[0]]);
    i = TOKEN.lastIndex;
  }
  return { toks: out };
}

function ident(kind, text) {
  if (kind === "qid") {
    const t = text.slice(1, -1);
    return text[0] === '"' ? t.replace(/""/g, '"') : t;
  }
  return text;
}
const eq = (a, k, t) => !!a && a[0] === k && a[1] === t;

function inFrom(low, i) {
  let depth = 0;
  for (let j = i - 1; j >= 0; j--) {
    const [k, t] = low[j];
    if (k === "op" && t === ")") depth++;
    else if (k === "op" && t === "(") { if (depth === 0) return false; depth--; }
    else if (depth === 0 && k === "word") {
      if (t === "from" || t === "join") return true;
      if (["select", "where", "group", "order", "having", "limit", "on", "using", "window", "union", "values"].includes(t)) return false;
    }
  }
  return false;
}

// checkSql(sql, table, columns, hidden?) -> {ok: true, sql} | {ok: false, reason}
export function checkSql(sql, table, columns, hidden) {
  if (typeof sql !== "string" || !sql.trim()) return { ok: false, reason: "no SQL" };
  if (sql.length > ANALYST_LIMITS.maxSqlChars) return { ok: false, reason: "longer than " + ANALYST_LIMITS.maxSqlChars + " characters" };
  const tk = tokens(sql);
  if (tk.error) return { ok: false, reason: tk.error };
  let toks = tk.toks;
  while (toks.length && eq(toks[toks.length - 1], "op", ";")) toks = toks.slice(0, -1);
  if (!toks.length) return { ok: false, reason: "no SQL" };
  if (toks.some((x) => eq(x, "op", ";"))) return { ok: false, reason: "more than one statement" };
  if (toks[0][0] !== "word" || !["select", "with"].includes(toks[0][1].toLowerCase())) return { ok: false, reason: "only a SELECT or WITH query is allowed" };
  const TABLE = String(table).toLowerCase();
  const cols = new Set(columns.map((c) => String(c).toLowerCase()));
  const hid = new Map((hidden || []).map((h) => [String(h).toLowerCase(), h]));
  const low = toks.map(([k, t]) => [k, t.toLowerCase()]);
  const defined = new Set();
  for (let i = 0; i < low.length; i++) {
    const [k, t] = low[i];
    if (k !== "word" && k !== "qid") continue;
    const nm = ident(k, toks[i][1]).toLowerCase();
    if (eq(low[i + 1], "word", "as") && eq(low[i + 2], "op", "(")) defined.add(nm);
    if (i > 0 && eq(low[i - 1], "word", "as")) defined.add(nm);
    if (eq(low[i + 1], "op", "(") && k === "word" && !FUNCTIONS.has(t) && !KEYWORDS.has(t)) {
      let depth = 0, j = i + 1;
      for (; j < low.length; j++) {
        if (eq(low[j], "op", "(")) depth++;
        else if (eq(low[j], "op", ")")) { depth--; if (depth === 0) break; }
      }
      if (eq(low[j + 1], "word", "as") && eq(low[j + 2], "op", "(")) {
        defined.add(nm);
        for (let q = i + 2; q < j; q++) if (low[q][0] === "word" || low[q][0] === "qid") defined.add(ident(low[q][0], toks[q][1]).toLowerCase());
      }
    }
  }
  for (let i = 0; i < low.length; i++) {
    if (eq(low[i], "word", "from") || eq(low[i], "word", "join")) {
      let j = i + 1;
      if (low[j] && (low[j][0] === "word" || low[j][0] === "qid")) {
        j++;
        if (eq(low[j], "word", "as")) j++;
        if (low[j] && (low[j][0] === "word" || low[j][0] === "qid") && !KEYWORDS.has(low[j][1])) defined.add(ident(low[j][0], toks[j][1]).toLowerCase());
      }
    }
  }
  for (let i = 0; i < low.length; i++) {
    const [k, t] = low[i];
    if (k === "word" && BANNED.has(t)) return { ok: false, reason: toks[i][1].toUpperCase() + " is not allowed: the query may only read" };
    if (k === "word" && t === "replace" && !eq(low[i + 1], "op", "(")) return { ok: false, reason: "REPLACE is not allowed: the query may only read" };
    if (k !== "word" && k !== "qid") continue;
    const raw = ident(k, toks[i][1]), nm = raw.toLowerCase();
    if (hid.has(nm)) return { ok: false, reason: hid.get(nm) + " is a column the visitor withheld or coded" };
    const prev = low[i - 1] || ["", ""];
    if (eq(prev, "word", "from") || eq(prev, "word", "join") || (eq(prev, "op", ",") && inFrom(low, i))) {
      if (nm !== TABLE && !defined.has(nm)) return { ok: false, reason: "only the table " + table + " can be read (not " + raw + ")" };
      continue;
    }
    if (k === "word" && eq(low[i + 1], "op", "(") && !KEYWORDS.has(t) && !FUNCTIONS.has(t) && !defined.has(nm)) return { ok: false, reason: "the function " + raw + " is not allowed" };
    if (k === "word" && (KEYWORDS.has(t) || FUNCTIONS.has(t))) continue;
    if (cols.has(nm) || nm === TABLE || defined.has(nm)) continue;
    if (k === "qid" && toks[i][1][0] === '"') return { ok: false, reason: toks[i][1] + " is not a column of " + table + " (write text values in single quotes)" };
    return { ok: false, reason: raw + " is not a column of " + table };
  }
  let text = sql.trim();
  while (text.endsWith(";")) text = text.slice(0, -1).trimEnd();
  return { ok: true, sql: text };
}

// ------------------------------------------------------------------------------------------ the model's answer form
// The structured-output form is flat (every field present; "" / [] / 0 for unused) because a strict output schema
// cannot hold the per-op variants; handleAnalyst turns each item into {op, args, why} and checks it against the
// canonical schema (narrowSchema) before anything leaves the worker.
export function outputSchema(ops) {
  return {
    type: "object",
    additionalProperties: false,
    required: ["steps", "done"],
    properties: {
      done: { type: "boolean" },
      steps: {
        type: "array",
        maxItems: ANALYST_LIMITS.maxStepsPerRound,
        items: {
          type: "object",
          additionalProperties: false,
          required: [
            "op",
            "measure",
            "measures",
            "by",
            "where_column",
            "where_value",
            "years",
            "denominator",
            "less",
            "grain",
            "period",
            "sql",
            "why",
          ],
          properties: {
            op: { type: "string", enum: ops },
            measure: { type: "string" },
            measures: { type: "array", items: { type: "string" } },
            by: { type: "string" },
            where_column: { type: "string" },
            where_value: { type: "string" },
            years: { type: "integer" },
            denominator: { type: "string" },
            less: { type: "string" },
            grain: { type: "string" },
            period: { type: "string" },
            sql: { type: "string" },
            why: { type: "string" },
          },
        },
      },
    },
  };
}

function fromFlat(s) {
  const args = {};
  if (s.measure) args.measure = s.measure;
  if (Array.isArray(s.measures) && s.measures.length)
    args.measures = s.measures;
  if (s.by) args.by = s.by;
  if (s.where_column)
    args.where = { [s.where_column]: String(s.where_value || "") };
  if (Number.isInteger(s.years) && s.years > 0) args.years = s.years;
  if (s.denominator) args.denominator = s.denominator;
  if (s.less) args.less = s.less;
  if (s.grain) args.grain = s.grain;
  if (s.period) args.period = s.period;
  if (s.sql) args.sql = s.sql;
  return { op: s.op, args, why: typeof s.why === "string" ? s.why : "" };
}

// ---------------------------------------------------------------------------------------------- input checks
function str(x, max) {
  return typeof x === "string" && x.length <= max;
}

export function cleanShape(shape) {
  if (!shape || typeof shape !== "object" || !SHAPE_KINDS.has(shape.kind))
    return null;
  const L = ANALYST_LIMITS;
  const measures = (Array.isArray(shape.measures) ? shape.measures : [])
    .filter(
      (m) => m && str(m.column, L.maxNameChars) && MEASURE_KINDS.has(m.kind),
    )
    .slice(0, L.maxColumns)
    .map((m) => ({ column: m.column, kind: m.kind }));
  const dimensions = (Array.isArray(shape.dimensions) ? shape.dimensions : [])
    .filter((d) => str(d, L.maxNameChars))
    .slice(0, L.maxColumns);
  const one = (x) => (str(x, L.maxNameChars) ? x : null);
  return {
    kind: shape.kind,
    date: one(shape.date),
    grain: one(shape.grain),
    entity: one(shape.entity),
    primary: one(shape.primary),
    label: one(shape.label),
    measures,
    dimensions,
  };
}

export function cleanPrior(steps) {
  const L = ANALYST_LIMITS;
  if (!Array.isArray(steps)) return null;
  const out = [];
  for (const s of steps.slice(-L.maxPriorSteps)) {
    if (!s || typeof s !== "object") return null;
    // ledger texts only: a step carrying a table, rows or raw values is refused as a whole (PROTOCOL.md)
    if ("table" in s || "rows" in s || "numbers" in s) return null;
    const figures = {};
    const f = s.figures && typeof s.figures === "object" ? s.figures : {};
    for (const k of Object.keys(f).slice(0, L.maxFiguresPerStep)) {
      if (/^[a-z0-9_]{1,40}$/.test(k) && str(f[k], L.maxFigureChars))
        figures[k] = f[k];
    }
    out.push({
      id: str(s.id, 12) ? s.id : "",
      op: str(s.op, 40) ? s.op : "",
      ok: !!s.ok,
      args:
        s.args && typeof s.args === "object"
          ? JSON.stringify(s.args).length <= L.maxPriorArgsChars
            ? JSON.parse(JSON.stringify(s.args))
            : {}
          : {},
      refused: str(s.refused, 200) ? s.refused : "",
      figures,
    });
  }
  return out;
}

// --------------------------------------------------------------------------- the schema, narrowed to this file
// what the file must have for an op to run at all (nl_analyst.OP_NEEDS, carried in the schema as x-needs)
function shapeHas(shape, need) {
  if (need === "date") return !!shape.date;
  if (need === "entity") return !!shape.entity && !!shape.date;
  if (need === "label") return !!shape.label;
  if (need === "answers") return shape.dimensions.length >= 2;
  return true;
}

export function narrowSchema(shape) {
  const meas = shape.measures.map((m) => m.column);
  const dims = shape.dimensions.concat(shape.entity ? [shape.entity] : []);
  const variants = [];
  for (const v of STEP_SCHEMA.oneOf) {
    const args = v.properties.args;
    const props = {};
    let ok = true;
    for (const [k, spec] of Object.entries(args.properties)) {
      const s = JSON.parse(JSON.stringify(spec));
      const pool = (role) =>
        role === "measure" ? meas : role === "dimension" ? dims : null;
      if (pool(s["x-role"])) s.enum = pool(s["x-role"]);
      if (s.items && pool(s.items["x-role"]))
        s.items.enum = pool(s.items["x-role"]);
      if (s.propertyNames && pool(s.propertyNames["x-role"]))
        s.propertyNames.enum = pool(s.propertyNames["x-role"]);
      const empty =
        (s.enum && !s.enum.length) ||
        (s.items && s.items.enum && !s.items.enum.length) ||
        (s.propertyNames &&
          s.propertyNames.enum &&
          !s.propertyNames.enum.length);
      if (empty && args.required.includes(k)) ok = false;
      if (!empty) props[k] = s;
    }
    if (v.properties.op.const === "correlate" && meas.length < 2) ok = false;
    if (!shapeHas(shape, v["x-needs"] || "")) ok = false;
    if (ok)
      variants.push({
        op: v.properties.op.const,
        required: args.required,
        props,
      });
  }
  return variants;
}

// One step against the narrowed schema: the same rules as nl_analyst._check_step, so the engine refuses nothing this
// passes (and refuses again, with the same reasons, if a step was tampered with on the way).
export function checkStep(raw, variants, shape) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw))
    return { why: "not an object" };
  const v = variants.find((x) => x.op === raw.op);
  if (!v) return { why: "op not offered for this file" };
  const extra = Object.keys(raw).filter(
    (k) => !["op", "args", "why"].includes(k),
  );
  if (extra.length) return { why: "unknown field" };
  const args =
    raw.args && typeof raw.args === "object" && !Array.isArray(raw.args)
      ? raw.args
      : null;
  if (!args) return { why: "args must be an object" };
  for (const k of Object.keys(args))
    if (!(k in v.props)) return { why: "argument not offered: " + k };
  for (const k of v.required)
    if (!(k in args)) return { why: "missing argument: " + k };
  for (const [k, val] of Object.entries(args)) {
    const s = v.props[k];
    if (s.type === "string") {
      if (
        typeof val !== "string" ||
        val.length > s.maxLength ||
        (s.enum && !s.enum.includes(val)) ||
        (s.pattern && !new RegExp(s.pattern).test(val))
      )
        return { why: "bad " + k };
      if (s["x-check"] === "sql") {
        const cols = shape ? shapeColumns(shape) : [];
        const c = checkSql(val, SQL_TABLE, cols);
        if (!c.ok) return { why: "sql refused: " + c.reason };
        args[k] = c.sql;
      }
    } else if (s.type === "array") {
      if (
        !Array.isArray(val) ||
        val.length < s.minItems ||
        val.length > s.maxItems ||
        val.some(
          (x) =>
            typeof x !== "string" ||
            (s.items.enum && !s.items.enum.includes(x)),
        )
      )
        return { why: "bad " + k };
    } else if (s.type === "object") {
      const ks =
        val && typeof val === "object" && !Array.isArray(val)
          ? Object.keys(val)
          : null;
      if (!ks || !ks.length || ks.length > s.maxProperties)
        return { why: "bad " + k };
      for (const kk of ks) {
        if (s.propertyNames.enum && !s.propertyNames.enum.includes(kk))
          return { why: "bad " + k };
        if (
          typeof val[kk] !== "string" ||
          val[kk].length > s.additionalProperties.maxLength
        )
          return { why: "bad " + k };
      }
    } else if (s.type === "integer") {
      if (!Number.isInteger(val) || val < s.minimum || val > s.maximum)
        return { why: "bad " + k };
    } else {
      return { why: "bad " + k };
    }
  }
  let why =
    typeof raw.why === "string"
      ? raw.why.slice(0, ANALYST_LIMITS.maxWhyChars)
      : "";
  if (/\d/.test(why)) why = ""; // a reason never carries a figure
  return { step: { op: raw.op, args, why } };
}

// the columns an sql step may read: the shape's date, measures, dimensions, entity and label
export function shapeColumns(shape) {
  const out = [];
  const add = (c) => { if (typeof c === "string" && c && !out.includes(c)) out.push(c); };
  add(shape.date);
  (shape.measures || []).forEach((m) => add(m && m.column));
  (shape.dimensions || []).forEach(add);
  add(shape.entity);
  add(shape.label);
  return out;
}

function sameStep(a, b) {
  const key = (x) =>
    x.op + " " + JSON.stringify(x.args, Object.keys(x.args || {}).sort());
  return key(a) === key(b);
}

// ------------------------------------------------------------------------------------------------ the handler
function json(body, status = 200) {
  return new Response(JSON.stringify(body), {
    status,
    headers: {
      "Content-Type": "application/json",
      "Cache-Control": "no-store",
    },
  });
}

export async function handleAnalyst(request, env, opts = {}) {
  if (request.method !== "POST") return json({ error: "method" }, 405);
  const text = await request.text();
  if (text.length > ANALYST_LIMITS.maxBodyBytes)
    return json({ error: "too_large" }, 413);
  let body;
  try {
    body = JSON.parse(text);
  } catch (e) {
    return json({ error: "bad_json" }, 400);
  }
  const shape = cleanShape(body && body.shape);
  const prior = cleanPrior(body && body.steps_so_far);
  const round = body && body.round;
  const objective =
    typeof (body && body.objective) === "string"
      ? body.objective.slice(0, ANALYST_LIMITS.maxObjectiveChars)
      : "";
  if (!shape) return json({ error: "bad_shape" }, 400);
  if (!prior) return json({ error: "bad_steps_so_far" }, 400);
  if (!Number.isInteger(round) || round < 1 || round > ANALYST_LIMITS.maxRounds)
    return json({ error: "bad_round" }, 400);
  if (!env.DEEPSEEK_API_KEY && !env.ANTHROPIC_API_KEY)
    return json({ error: "not_configured" }, 503);

  const variants = narrowSchema(shape);
  if (!variants.length) return json({ steps: [], done: true, dropped: [] });
  const user = JSON.stringify({
    objective,
    round,
    max_rounds: ANALYST_LIMITS.maxRounds,
    shape,
    steps_so_far: prior,
    offered: variants.map((v) => ({
      op: v.op,
      required: v.required,
      args: Object.fromEntries(
        Object.entries(v.props).map(([k, s]) => [
          k,
          s.enum ||
            (s.items && s.items.enum) ||
            (s.propertyNames && s.propertyNames.enum) ||
            s.type,
        ]),
      ),
    })),
  });

  // the proxy's daily spend: one model call reserved before it is made (opts.reserve, from analystFetch)
  if (typeof opts.reserve === "function") {
    const rv = await opts.reserve();
    if (rv !== "ok") {
      return rv === "busy"
        ? json({ error: "busy" }, 429)
        : json({ error: rv === "not_configured" ? "not_configured" : rv === "failed" ? "daily_counter_failed" : "daily_cap_reached" }, 503);
    }
  }
  const got = env.DEEPSEEK_API_KEY
    ? await callDeepSeek(env, user, variants)
    : await callClaude(env, user, variants);
  if (got.error) return json({ error: got.error }, got.status);
  if (got.refused)
    return json({ steps: [], done: true, dropped: [], note: "refused" });
  const answer = got.answer;
  const msg = { model: got.model, usage: got.usage };

  const steps = [],
    dropped = [];
  const raw = Array.isArray(answer && answer.steps) ? answer.steps : [];
  raw.forEach((flat, i) => {
    if (steps.length >= ANALYST_LIMITS.maxStepsPerRound) {
      dropped.push({ index: i, why: "over the round's limit" });
      return;
    }
    const r = checkStep(fromFlat(flat || {}), variants, shape);
    if (!r.step) {
      dropped.push({ index: i, why: r.why });
      return;
    }
    if (
      prior.some((p) => sameStep(p, r.step)) ||
      steps.some((s) => sameStep(s, r.step))
    ) {
      dropped.push({ index: i, why: "already run" });
      return;
    }
    steps.push(r.step);
  });
  const done =
    !!(answer && answer.done) ||
    !steps.length ||
    round >= ANALYST_LIMITS.maxRounds;
  return json({
    steps,
    done,
    dropped,
    model: msg.model,
    usage: msg.usage,
  });
}

// ------------------------------------------------------------------------------------------------ the model calls
// Each returns {answer, model, usage} with the parsed answer form, {refused: true}, or {error, status} as the
// protocol names them (504 timeout, 429 busy, 502 upstream | bad_answer | truncated).
async function post(url, headers, body, env) {
  const ctrl = new AbortController();
  const timer = setTimeout(
    () => ctrl.abort(),
    Number(env.ANALYST_TIMEOUT_MS) || 25000,
  );
  try {
    const res = await fetch(url, {
      method: "POST",
      signal: ctrl.signal,
      headers: Object.assign({ "content-type": "application/json" }, headers),
      body: JSON.stringify(body),
    });
    if (!res.ok)
      return res.status === 429
        ? { error: "busy", status: 429 }
        : { error: "upstream", status: 502 };
    return { res: await res.json() };
  } catch (e) {
    return ctrl.signal.aborted
      ? { error: "timeout", status: 504 }
      : { error: "upstream", status: 502 };
  } finally {
    clearTimeout(timer);
  }
}

function parseAnswer(text) {
  // the answer as one JSON object; a model that wraps it in a code fence or a sentence still parses, from the first
  // "{" to the last "}"
  const t = String(text || "").trim();
  for (const cand of [t, t.slice(t.indexOf("{"), t.lastIndexOf("}") + 1)]) {
    try {
      const a = JSON.parse(cand);
      if (a && typeof a === "object" && !Array.isArray(a)) return a;
    } catch (e) {
      /* try the next reading */
    }
  }
  return null;
}

function deepseekBase(env) {
  const raw = String(env.DEEPSEEK_BASE_URL || "").trim();
  if (!raw) return "https://api.deepseek.com";
  try {
    const u = new URL(raw);
    return u.protocol === "https:" ? u.origin + u.pathname.replace(/\/+$/, "") : "https://api.deepseek.com";
  } catch (e) {
    return "https://api.deepseek.com";
  }
}

// DeepSeek (OpenAI-compatible chat API). Nothing guarantees the schema, so the answer form is
// spelled out in the system turn and every step is still checked by checkStep before it leaves the worker.
export async function callDeepSeek(env, user, variants) {
  const form = JSON.stringify(outputSchema(variants.map((v) => v.op)));
  // the same base and model as the proxy's /plan and /report (DEEPSEEK_BASE_URL, DEEPSEEK_MODEL; "deepseek-chat" was
  // retired on 2026-07-24). No JSON mode: the proxy reads JSON from plain text, and so does parseAnswer.
  const r = await post(
    deepseekBase(env) + "/chat/completions",
    { authorization: "Bearer " + String(env.DEEPSEEK_API_KEY).trim() },
    {
      model: String(env.DEEPSEEK_MODEL || "deepseek-flash").trim(),
      temperature: 0,
      max_tokens: Math.min(Number(env.ANALYST_MAX_TOKENS) || 2000, 8000),
      messages: [
        {
          role: "system",
          content:
            SYSTEM_PROMPT +
            "\n\nAnswer with one JSON object of this JSON schema, every field present:\n" +
            form,
        },
        { role: "user", content: user },
      ],
    },
    env,
  );
  if (r.error) return r;
  const choice = (r.res.choices || [])[0] || {};
  if (choice.finish_reason === "length")
    return { error: "truncated", status: 502 };
  if (choice.finish_reason === "content_filter") return { refused: true };
  const answer = parseAnswer(choice.message && choice.message.content);
  if (!answer) return { error: "bad_answer", status: 502 };
  const u = r.res.usage || {};
  return {
    answer,
    model: r.res.model,
    usage: { input_tokens: u.prompt_tokens, output_tokens: u.completion_tokens },
  };
}

// Claude (Messages API), structured output against the flat answer form.
export async function callClaude(env, user, variants) {
  const r = await post(
    "https://api.anthropic.com/v1/messages",
    {
      "x-api-key": env.ANTHROPIC_API_KEY,
      "anthropic-version": "2023-06-01",
      // a declined request is re-run server-side on Anthropic's recommended fallback model
      "anthropic-beta": "server-side-fallback-2026-07-01",
    },
    {
      model: env.ANALYST_MODEL || "claude-opus-5-5",
      max_tokens: Number(env.ANALYST_MAX_TOKENS) || 4000,
      fallbacks: "default",
      output_config: {
        effort: env.ANALYST_EFFORT || "low",
        format: {
          type: "json_schema",
          schema: outputSchema(variants.map((v) => v.op)),
        },
      },
      system: [
        { type: "text", text: SYSTEM_PROMPT, cache_control: { type: "ephemeral" } },
      ],
      messages: [{ role: "user", content: user }],
    },
    env,
  );
  if (r.error) return r;
  const msg = r.res;
  if (msg.stop_reason === "refusal") return { refused: true };
  if (msg.stop_reason === "max_tokens") return { error: "truncated", status: 502 };
  const block = (msg.content || []).find((b) => b.type === "text");
  const answer = parseAnswer(block && block.text);
  if (!answer) return { error: "bad_answer", status: 502 };
  return {
    answer,
    model: msg.model,
    usage: msg.usage
      ? { input_tokens: msg.usage.input_tokens, output_tokens: msg.usage.output_tokens }
      : undefined,
  };
}

// ------------------------------------------------------------------------------------------------ the route in the proxy
// analystFetch(request, env): POST /analyst (and its OPTIONS preflight) behind the same gates as the proxy's /plan
// and /report, using the proxy's own bindings and vars, so wrangler.toml does not change:
//   ALLOWED_ORIGIN (comma list) for CORS, RATE_LIMITER (per network), GLOBAL_LIMITER (everyone together), SPEND (the
//   SpendCounter Durable Object: one DeepSeek call is reserved against DAILY_CAP before the model is asked).
// In the proxy's entry: `if (new URL(request.url).pathname === "/analyst") return analystFetch(request, env);`
// before its own routing. A missing binding refuses (503) rather than calling the model unmetered.
const ANALYST_DAILY_CAP = 300;
const ANALYST_MINUTE_LIMIT = 10;

function origins(env) {
  return String(env.ALLOWED_ORIGIN || "")
    .split(",")
    .map((s) => s.trim())
    .filter((s) => s && s !== "null" && s !== "*");
}

function withCors(res, origin) {
  const h = new Headers(res.headers);
  if (origin) {
    h.set("Access-Control-Allow-Origin", origin);
    h.set("Access-Control-Allow-Methods", "POST, OPTIONS");
    h.set("Access-Control-Allow-Headers", "Content-Type");
    h.set("Access-Control-Max-Age", "600");
  }
  h.set("Vary", "Origin");
  h.set("Cache-Control", "no-store");
  h.set("X-Content-Type-Options", "nosniff");
  return new Response(res.body, { status: res.status, headers: h });
}

async function limited(binding, key) {
  if (!binding || typeof binding.limit !== "function") return null; // no binding: the caller decides
  try {
    const r = await binding.limit({ key });
    return !r.success;
  } catch (e) {
    return null;
  }
}

async function reserveOne(env) {
  const ns = env.SPEND;
  if (!ns || typeof ns.idFromName !== "function" || typeof ns.get !== "function") return "not_configured";
  const posInt = (v, d) => (Number.isInteger(Number(v)) && Number(v) > 0 ? Number(v) : d);
  try {
    const res = await ns.get(ns.idFromName("global")).fetch("https://spend-counter/reserve", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        calls: 1,
        dailyCap: posInt(env.DAILY_CAP, ANALYST_DAILY_CAP),
        minuteLimit: posInt(env.GLOBAL_LIMIT_PER_MINUTE, ANALYST_MINUTE_LIMIT),
        kind: "llm",
      }),
    });
    if (!res || !res.ok) return "failed";
    const data = await res.json();
    if (data && data.ok === true) return "ok";
    // the same reading as the proxy's own reserveCalls: only these two refusals are named, anything else failed
    if (data && data.ok === false && (data.reason === "busy" || data.reason === "daily_cap_reached")) return data.reason;
    return "failed";
  } catch (e) {
    return "failed";
  }
}

export async function analystFetch(request, env) {
  const origin = request.headers.get("Origin");
  const allowed = origin !== null && origins(env).includes(origin) ? origin : null;
  if (request.method === "OPTIONS") {
    return allowed
      ? withCors(new Response(null, { status: 204 }), allowed)
      : new Response(null, { status: 403, headers: { Vary: "Origin" } });
  }
  if (!allowed) return withCors(json({ error: "origin_not_allowed" }, 403), null);
  if (request.method !== "POST") return withCors(json({ error: "method" }, 405), allowed);
  const ctype = (request.headers.get("Content-Type") || "").split(";")[0].trim().toLowerCase();
  if (ctype !== "application/json") return withCors(json({ error: "unsupported_media_type" }, 415), allowed);
  const ip = request.headers.get("CF-Connecting-IP") || "unknown";
  if ((await limited(env.RATE_LIMITER, "analyst:" + ip)) === true) {
    return withCors(json({ error: "rate_limited" }, 429), allowed);
  }
  if ((await limited(env.GLOBAL_LIMITER, "global")) === true) return withCors(json({ error: "busy" }, 429), allowed);
  // the body is read (and capped) by handleAnalyst; the spend is reserved only for a request that reaches the model
  const text = await request.text();
  if (text.length > ANALYST_LIMITS.maxBodyBytes) return withCors(json({ error: "too_large" }, 413), allowed);
  const res = await handleAnalyst(
    new Request(request.url, { method: "POST", headers: { "content-type": "application/json" }, body: text }),
    env,
    { reserve: () => reserveOne(env) },
  );
  return withCors(res, allowed);
}
